/** "Workout A", "B" … by day index. */
export const workoutName = (day: number): string => String.fromCharCode(65 + day);

/** A weight for a tip or a set: no trailing zeros, with its unit. */
export const formatWeight = (w: number, units: string): string => `${Number.isInteger(w) ? w : w.toFixed(1)} ${units}`;

/** A set in a list: "62.5 kg × 6", "12 reps", "30 s". */
export function formatSet(weight: number | null, reps: number, units: string, unit: 'reps' | 'seconds' = 'reps'): string {
  if (unit === 'seconds') return `${reps} s`;
  return weight !== null && weight > 0 ? `${formatWeight(weight, units)} × ${reps}` : `${reps} reps`;
}

/** Elapsed time, "18:42" or "1:05:09". */
export function formatClock(ms: number): string {
  const s = Math.max(0, Math.floor(ms / 1000));
  const h = Math.floor(s / 3600);
  const m = Math.floor((s % 3600) / 60);
  const sec = String(s % 60).padStart(2, '0');
  return h > 0 ? `${h}:${String(m).padStart(2, '0')}:${sec}` : `${m}:${sec}`;
}
